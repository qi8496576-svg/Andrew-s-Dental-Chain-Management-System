import { expect, test } from '@playwright/test'
test('headquarters grants within its scope and revocation immediately removes rights from an existing session', async ({ page, browser }) => {
  await page.goto('/authentication')
  await page.getByLabel('个人账号').fill(process.env.ADC_MANAGER_USERNAME!)
  await page.getByLabel('密码', { exact: true }).fill(process.env.ADC_MANAGER_PASSWORD!)
  await page.getByRole('button', { name: '登录管理后台' }).click()
  await page.getByRole('button', { name: '打开管理中心', exact: true }).click()
  await page.getByRole('dialog', { name: '系统管理与基础配置', exact: true }).getByRole('link', { name: '角色、岗位与诊所授权', exact: true }).click()
  await expect(page.getByText('当前可管理诊所：诊所 1', { exact: true })).toBeVisible()
  const accounts = await (await page.request.get('/api/v1/identity/staff-accounts')).json()
  const target = accounts.items.find((account: { username: string }) => account.username === process.env.ADC_TEST_USERNAME).subject_id as string
  await page.getByLabel('员工主体标识筛选').fill(target)
  await page.getByRole('button', { name: '筛选 / 刷新' }).click()
  await page.getByRole('button', { name: '建立授权' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('员工主体标识', { exact: true }).fill(target)
  await dialog.getByLabel('岗位', { exact: true }).selectOption('RECEPTION')
  await dialog.getByLabel('诊所 1', { exact: true }).check()
  await dialog.getByLabel('创建预约', { exact: true }).check()
  await dialog.getByLabel('已核对本次岗位、诊所及权限变更依据').check()
  await dialog.getByRole('button', { name: '确认授权变更' }).click()
  await expect(dialog).not.toBeVisible()
  const grant = page.getByRole('row').filter({ hasText: target }).filter({ hasText: '前台' })
  await expect(grant).toBeVisible()
  if (process.env.ADC_GRANT_SCREENSHOT) await page.screenshot({ path: process.env.ADC_GRANT_SCREENSHOT, fullPage: true })
  const employee = await browser.newContext({ ignoreHTTPSErrors: true })
  try {
    const employeePage = await employee.newPage()
    await employeePage.goto(`${process.env.ADC_AUTH_BASE_URL}/authentication`)
    await employeePage.getByLabel('个人账号').fill(process.env.ADC_TEST_USERNAME!)
    await employeePage.getByLabel('密码', { exact: true }).fill(process.env.ADC_TEST_PASSWORD!)
    await employeePage.getByRole('button', { name: '登录管理后台' }).click()
    await expect(employeePage.getByRole('heading', { name: '管理后台', exact: true })).toBeVisible()
    expect((await (await employee.request.get(`${process.env.ADC_AUTH_BASE_URL}/api/v1/me`)).json()).capabilities).toContain('createAppointment')
    expect((await employee.request.get(`${process.env.ADC_AUTH_BASE_URL}/api/v1/identity/grants`)).status()).toBe(403)
    await grant.getByRole('button', { name: '撤销', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('撤销原因').fill('verified fixture authorization revocation')
    await dialog.getByLabel('已核对本次岗位、诊所及权限变更依据').check()
    await dialog.getByRole('button', { name: '确认授权变更' }).click()
    await expect(dialog).not.toBeVisible()
    await expect(grant.getByText('已撤销', { exact: true })).toBeVisible()
    const current = await employee.request.get(`${process.env.ADC_AUTH_BASE_URL}/api/v1/me`)
    expect(current.status()).toBe(200)
    expect((await current.json()).capabilities).not.toContain('createAppointment')
  } finally { await employee.close() }
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
})

