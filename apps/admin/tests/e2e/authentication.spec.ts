import { expect, test } from '@playwright/test'
test('real HTTPS login, current identity, navigation, refresh and logout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  if (process.env.ADC_LOGIN_SCREENSHOT) await page.screenshot({ path: process.env.ADC_LOGIN_SCREENSHOT, fullPage: true })
  await page.getByLabel('个人账号').fill(process.env.ADC_TEST_USERNAME!)
  await page.getByLabel('密码', { exact: true }).fill(process.env.ADC_TEST_PASSWORD!)
  await page.getByRole('button', { name: '登录管理后台' }).click()
  await expect(page.getByRole('heading', { name: '把今天的工作，安排清楚', exact: true })).toBeVisible()
  const toggle = page.getByRole('button', { name: '切换导航' })
  await toggle.click(); await expect(page.getByRole('navigation', {name:'主导航',exact:true})).toBeHidden(); await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click(); await expect(page.getByRole('navigation', {name:'主导航',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '把今天的工作，安排清楚', exact: true })).toBeVisible()
  const cookies = await page.context().cookies()
  const session = cookies.find(cookie => cookie.name === 'adc_session')
  expect(session?.httpOnly).toBe(true); expect(session?.secure).toBe(true); expect(session?.sameSite).toBe('Lax')
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  expect(errors).toEqual([])
})
test('invalid credentials show a generic error and clear the password field', async ({ page }) => {
  await page.goto('/authentication')
  await page.getByLabel('个人账号').fill(process.env.ADC_TEST_USERNAME!)
  await page.getByLabel('密码', { exact: true }).fill('wrong-fixture-password')
  await page.getByRole('button', { name: '登录管理后台' }).click()
  await expect(page.getByRole('alert')).toContainText('账号或密码无效')
  await expect(page.getByLabel('密码', { exact: true })).toHaveValue('')
})

