import { expect, test } from '@playwright/test'
test('headquarters verifies accounts, recovers credentials and revokes old sessions without granting business privileges', async ({ page, browser }) => {
  await page.goto('/authentication')
  await page.getByLabel('个人账号').fill(process.env.ADC_MANAGER_USERNAME!)
  await page.getByLabel('密码', { exact: true }).fill(process.env.ADC_MANAGER_PASSWORD!)
  await page.getByRole('button', { name: '登录管理后台' }).click()
  await page.getByRole('link', { name: '员工账号', exact: true }).click()
  await expect(page.getByRole('heading', { name: '员工账号', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '建立员工账号' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('个人账号').fill('browser-created-employee')
  await dialog.getByLabel('工作人员核实依据').fill('verified isolated browser fixture')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '确认办理' }).click()
  await expect(dialog).not.toBeVisible()
  const account = page.getByRole('row').filter({ hasText: 'browser-created-employee' })
  await expect(account).toBeVisible()
  await account.getByRole('button', { name: '密码管理' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('操作原因').fill('verified credential setup')
  await dialog.getByLabel('本人及员工核验依据', { exact: true }).fill('verified fixture evidence')
  await dialog.getByLabel('新密码').fill(process.env.ADC_RECOVERED_PASSWORD!)
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '确认办理' }).click()
  await expect(dialog).not.toBeVisible()
  const employee = await browser.newContext({ ignoreHTTPSErrors: true })
  try {
    const employeePage = await employee.newPage()
    await employeePage.goto(`${process.env.ADC_AUTH_BASE_URL}/authentication`)
    await employeePage.getByLabel('个人账号').fill('browser-created-employee')
    await employeePage.getByLabel('密码', { exact: true }).fill(process.env.ADC_RECOVERED_PASSWORD!)
    await employeePage.getByRole('button', { name: '登录管理后台' }).click()
    await expect(employeePage.getByRole('heading', { name: '管理后台', exact: true })).toBeVisible()
    await expect(employeePage.getByRole('link', { name: '员工账号', exact: true })).toHaveCount(0)
    const unauthorized = await employee.request.get(`${process.env.ADC_AUTH_BASE_URL}/api/v1/identity/staff-accounts`)
    expect(unauthorized.status()).toBe(403)
    const oldSession = (await employee.cookies()).find(cookie => cookie.name === 'adc_session')!
    for (const action of ['停用', '启用']) {
      await account.getByRole('button', { name: action, exact: true }).click()
      dialog = page.getByRole('dialog')
      await dialog.getByLabel('操作原因').fill(`verified fixture ${action}`)
      await dialog.getByRole('checkbox').check()
      await dialog.getByRole('button', { name: '确认办理' }).click()
      await expect(dialog).not.toBeVisible()
      await expect(account.getByText(action === '停用' ? '已停用' : '已启用', { exact: true })).toBeVisible()
    }
    await employee.addCookies([oldSession])
    expect((await employee.request.get(`${process.env.ADC_AUTH_BASE_URL}/api/v1/me`)).status()).toBe(401)
  } finally { await employee.close() }
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
})

