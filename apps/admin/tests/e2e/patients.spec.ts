import { expect, test } from '@playwright/test'
import type { components } from '@adc/contracts'

test('reception verifies an actual patient, preserves allergy history and loses access immediately on revocation',async({page,browser})=>{
  const manager=await browser.newContext({ignoreHTTPSErrors:true})
  try{
    const root=process.env.ADC_AUTH_BASE_URL!
    const init=await (await manager.request.get(`${root}/api/v1/auth/csrf`)).json()
    const login=await manager.request.post(`${root}/api/v1/auth/staff-sessions`,{headers:{'X-CSRF-Token':init.csrf_token,Origin:root},data:{username:process.env.ADC_MANAGER_USERNAME,password:process.env.ADC_MANAGER_PASSWORD}})
    expect(login.status()).toBe(200)
    const csrf=(await login.json()).csrf_token
    const accounts=await (await manager.request.get(`${root}/api/v1/identity/staff-accounts`)).json()
    const target=accounts.items.find((account:{username:string})=>account.username===process.env.ADC_TEST_USERNAME).subject_id
    const grantBody:components['schemas']['GrantCreate']={subject_id:target,role:'RECEPTION',clinic_ids:['1'],capabilities:['createPatient','getPatient','updatePatient','reviewPatientAllergies','addPatientAllergy','listPatientAllergies','correctPatientAllergy','retractPatientAllergy'],valid_from:new Date().toISOString(),valid_until:null}
    const grantResponse=await manager.request.post(`${root}/api/v1/identity/grants`,{headers:{'X-CSRF-Token':csrf,Origin:root,'Idempotency-Key':crypto.randomUUID()},data:grantBody})
    expect(grantResponse.status()).toBe(200);const grant=await grantResponse.json()
    await page.goto('/authentication');await page.getByLabel('个人账号').fill(process.env.ADC_TEST_USERNAME!);await page.getByLabel('密码',{exact:true}).fill(process.env.ADC_TEST_PASSWORD!)
    const loggedIn=page.waitForResponse(response=>response.url().endsWith('/api/v1/auth/staff-sessions') && response.request().method()==='POST')
    await page.getByRole('button',{name:'登录管理后台'}).click()
    const employeeCsrf=(await (await loggedIn).json()).csrf_token
    const malformed=await page.request.post('/api/v1/patients',{headers:{'X-CSRF-Token':employeeCsrf,Origin:root,'Idempotency-Key':crypto.randomUUID()},data:{full_name:'Rejected numeric ID fixture',date_of_birth:'1990-01-02',phone:'000',billing_address:'Fixture',emergency_contact_name:'Fixture',emergency_contact_phone:'000',verification_basis:{clinic_id:1,person_confirmed:true,service_basis:'fixture'}}})
    expect(malformed.status()).toBe(400)
    await page.getByRole('link',{name:'患者资料',exact:true}).click()
    await page.getByLabel('服务依据',{exact:true}).fill('Fictional in-person UC05 acceptance visit')
    await page.getByLabel('已核实患者本人及原资料').check()
    await page.getByRole('button',{name:'新患者建档'}).click()
    await page.getByLabel('姓名',{exact:true}).fill('虚构患者 陈晓')
    await page.getByLabel('档案出生日期',{exact:true}).fill('1990-01-02')
    await page.getByLabel('联系电话',{exact:true}).fill('000-1001')
    await page.getByLabel('账单地址',{exact:true}).fill('隔离验收测试地址')
    await page.getByLabel('紧急联系人',{exact:true}).fill('虚构联系人')
    await page.getByLabel('紧急联系电话',{exact:true}).fill('000-1002')
    const creation=page.waitForResponse(response=>response.url().endsWith('/api/v1/patients') && response.request().method()==='POST')
    await page.getByRole('button',{name:'保存患者资料',exact:true}).click()
    const response=await creation;expect(response.status()).toBe(200);const patient=await response.json()
    await expect(page.getByRole('heading',{name:'虚构患者 陈晓'})).toBeVisible()
    await page.getByLabel('患者编号',{exact:true}).fill(patient.patient_number)
    await page.getByLabel('出生日期',{exact:true}).fill('1990-01-02')
    await page.getByRole('button',{name:'核验并查找档案'}).click()
    await expect(page.getByRole('status')).toHaveText('本人资料及本次服务依据已核验。')
    await page.getByRole('button',{name:'核实过敏状态'}).click()
    let dialog=page.getByRole('dialog')
    await dialog.getByLabel('询问核实结果').selectOption('NO_KNOWN')
    await dialog.getByLabel('核实及操作原因').fill('已向本人询问暂无已知过敏')
    await dialog.getByRole('button',{name:'确认保存核实结果'}).click()
    await expect(dialog).not.toBeVisible();await expect(page.locator('.risk-banner')).toContainText('经询问无已知过敏')
    await page.getByRole('button',{name:'新增过敏记录'}).click();dialog=page.getByRole('dialog')
    await dialog.getByLabel('过敏目录').selectOption({label:'Fixture allergy'})
    await dialog.getByLabel('过敏程度',{exact:true}).fill('轻度')
    await dialog.getByLabel('临床备注',{exact:true}).fill('本次询问补充的虚构风险')
    await dialog.getByLabel('核实及操作原因').fill('本人补充并已核实')
    await dialog.getByRole('button',{name:'确认保存核实结果'}).click();await expect(dialog).not.toBeVisible()
    let row=page.getByRole('row').filter({hasText:'Fixture allergy'});await expect(row).toContainText('轻度')
    await row.getByRole('button',{name:'更正',exact:true}).click();dialog=page.getByRole('dialog')
    await dialog.getByLabel('过敏程度',{exact:true}).fill('重度')
    await dialog.getByLabel('核实及操作原因').fill('核实后更正程度')
    await dialog.getByRole('button',{name:'确认保存核实结果'}).click();await expect(dialog).not.toBeVisible();await expect(row).toContainText('重度')
    if(process.env.ADC_PATIENT_SCREENSHOT)await page.screenshot({path:process.env.ADC_PATIENT_SCREENSHOT,fullPage:true})
    await row.getByRole('button',{name:'撤销误记'}).click();dialog=page.getByRole('dialog')
    await dialog.getByLabel('核实及操作原因').fill('已核实为误记，保留原核实历史')
    await dialog.getByRole('button',{name:'确认保存核实结果'}).click();await expect(dialog).not.toBeVisible();await expect(row).toContainText('已撤销误记');await expect(page.locator('.risk-banner')).toContainText('尚未核实')
    await page.getByRole('button',{name:'更正基本资料'}).click();await page.getByLabel('联系电话',{exact:true}).fill('000-2001')
    await page.getByRole('button',{name:'保存患者资料',exact:true}).click();await expect(page.locator('.patient-summary')).toContainText('000-2001')
    const revoke=await manager.request.post(`${root}/api/v1/identity/grants/${grant.grant_id}/revoke`,{headers:{'X-CSRF-Token':csrf,Origin:root,'Idempotency-Key':crypto.randomUUID()},data:{reason:'verified fixture role revocation',verification_reference:'isolated test'}});expect(revoke.status()).toBe(200)
    await page.getByRole('button',{name:'重新读取资料'}).click();await expect(page).toHaveURL(`${root}/`);await expect(page.getByRole('heading',{name:'虚构患者 陈晓'})).not.toBeVisible();await expect(page.getByRole('link',{name:'患者资料',exact:true})).not.toBeVisible()
    await page.getByRole('button',{name:'退出登录'}).click();await expect(page.getByRole('heading',{name:'欢迎回来'})).toBeVisible()
  }finally{await manager.close()}
})

